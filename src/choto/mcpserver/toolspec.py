MISSION_START_DESCRIPTION = (
    "Write down what a long run is for, before you lose it. Halfway through a "
    "twenty-window scenario the plan has scrolled out of your context and what "
    "is left is a confident recollection of it — a mission is that plan kept "
    "outside you, in the server's database. goal is what the whole run is for. "
    "items is the checklist in order, each {title, intent, acceptance}: what to "
    "do, WHY it is on the list, and what would make it done. All three are "
    "required and none may be blank — intent and acceptance are the two you "
    "will no longer have when you read this back, and they are the reason the "
    "record is worth keeping at all. "
    "THE LOOP: mission_start -> work item by item, running each with "
    "execute_plan(steps=[...], mission_item_id=N) so the run files its own "
    "verdict and its steps onto item N -> the status block comes back on every "
    "reply, so you never have to remember where you are -> repeat a recorded "
    "pass later with mission_replay(N) -> mission_finish when there is nothing "
    "left to try. "
    "One mission is active at a time: starting a second while one runs is "
    "refused, naming the one to finish or abandon first. The reply is the "
    "status block — goal, progress, the item now in play with its intent and "
    "acceptance, and any failures with their reasons."
)

